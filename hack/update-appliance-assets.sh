#!/usr/bin/env bash
# Regenerates appliance/assets.lock and appliance/clusterctl.yaml - the
# pinned, checksummed set of upstream files Dockerfile.appliance bakes into
# the single-container appliance (Flux's install.yaml, clusterctl, and a
# clusterctl local repository holding Cluster API, cert-manager and every
# infrastructure provider the web UI can enable). To ship another
# infrastructure provider, add its components/metadata under
# clusterctl/repo/infrastructure-<name>/<version>/ and to clusterctl.yaml. Bump a version below, run `make appliance-assets`,
# review the diff.
#
# Checksums come from GitHub's own per-asset digests, so a later tampered or
# re-uploaded asset fails the image build instead of shipping silently.
set -euo pipefail

K3S_VERSION="v1.36.5-k3s1"
FLUX_VERSION="v2.9.6"
CAPI_VERSION="v1.14.3"
CERT_MANAGER_VERSION="v1.21.2"
# Every infrastructure provider the web UI can enable, as
# <clusterctl name>:<GitHub repo>:<version> - each release must publish
# infrastructure-components.yaml and metadata.yaml. E.g. adding
# "aws:kubernetes-sigs/cluster-api-provider-aws:v2.9.0" ships AWS too (the
# operator still needs its own WorkloadCluster support to use it).
INFRASTRUCTURE_PROVIDERS=(
    "incus:lxc/cluster-api-provider-incus:v0.9.1"
)

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="/opt/akbench/clusterctl/repo"

# No associative arrays: this has to run on macOS's bash 3.2 too.
RELEASE_JSON="$(mktemp)"
trap 'rm -f "$RELEASE_JSON"' EXIT
fetch_digests() {
    local repo="$1" tag="$2" auth=()
    if [[ -n "${GITHUB_TOKEN:-}" ]]; then
        auth=(-H "Authorization: Bearer ${GITHUB_TOKEN}")
    fi
    curl -fsSL ${auth[@]+"${auth[@]}"} "https://api.github.com/repos/${repo}/releases/tags/${tag}" >"$RELEASE_JSON"
}

lock=()
add() {
    local repo="$1" tag="$2" asset="$3" dest="$4" sum
    sum="$(jq -r --arg name "$asset" '.assets[] | select(.name == $name) | .digest // empty' "$RELEASE_JSON")"
    sum="${sum#sha256:}"
    if [[ -z "$sum" ]]; then
        echo "no digest for ${repo}@${tag}/${asset}" >&2
        exit 1
    fi
    lock+=("${sum}  ${dest}  https://github.com/${repo}/releases/download/${tag}/${asset}")
}

fetch_digests fluxcd/flux2 "$FLUX_VERSION"
add fluxcd/flux2 "$FLUX_VERSION" install.yaml flux/install.yaml

fetch_digests kubernetes-sigs/cluster-api "$CAPI_VERSION"
for arch in amd64 arm64; do
    add kubernetes-sigs/cluster-api "$CAPI_VERSION" "clusterctl-linux-${arch}" "bin/clusterctl-linux-${arch}"
done
for p in cluster-api:core-components.yaml bootstrap-kubeadm:bootstrap-components.yaml control-plane-kubeadm:control-plane-components.yaml; do
    label="${p%%:*}" file="${p#*:}"
    add kubernetes-sigs/cluster-api "$CAPI_VERSION" "$file" "clusterctl/repo/${label}/${CAPI_VERSION}/${file}"
    add kubernetes-sigs/cluster-api "$CAPI_VERSION" metadata.yaml "clusterctl/repo/${label}/${CAPI_VERSION}/metadata.yaml"
done

infra_config=""
for p in "${INFRASTRUCTURE_PROVIDERS[@]}"; do
    IFS=: read -r name repo version <<<"$p"
    fetch_digests "$repo" "$version"
    for file in infrastructure-components.yaml metadata.yaml; do
        add "$repo" "$version" "$file" "clusterctl/repo/infrastructure-${name}/${version}/${file}"
    done
    infra_config+="  - name: ${name}
    type: InfrastructureProvider
    url: file://${REPO}/infrastructure-${name}/${version}/infrastructure-components.yaml
"
done

fetch_digests cert-manager/cert-manager "$CERT_MANAGER_VERSION"
add cert-manager/cert-manager "$CERT_MANAGER_VERSION" cert-manager.yaml "clusterctl/repo/cert-manager/${CERT_MANAGER_VERSION}/cert-manager.yaml"

k3s_digest="$(docker buildx imagetools inspect "rancher/k3s:${K3S_VERSION}" --format '{{json .Manifest.Digest}}' | tr -d '"')"

{
    echo "# Generated by hack/update-appliance-assets.sh - do not edit by hand."
    echo "# k3s-image: rancher/k3s:${K3S_VERSION}@${k3s_digest}"
    echo "# <sha256>  <path under /opt/akbench>  <url>"
    printf '%s\n' "${lock[@]}"
} >"${ROOT}/appliance/assets.lock"

cat >"${ROOT}/appliance/clusterctl.yaml" <<EOF
# Generated by hack/update-appliance-assets.sh - do not edit by hand.
# Every provider comes from the local repository baked into the image, so
# clusterctl never reaches GitHub at runtime (the versions installed are
# exactly the ones the image was built and tested with). Listing an
# infrastructure provider here doesn't install it - enabling it in the web
# UI does.
providers:
  - name: cluster-api
    type: CoreProvider
    url: file://${REPO}/cluster-api/${CAPI_VERSION}/core-components.yaml
  - name: kubeadm
    type: BootstrapProvider
    url: file://${REPO}/bootstrap-kubeadm/${CAPI_VERSION}/bootstrap-components.yaml
  - name: kubeadm
    type: ControlPlaneProvider
    url: file://${REPO}/control-plane-kubeadm/${CAPI_VERSION}/control-plane-components.yaml
${infra_config}cert-manager:
  url: file://${REPO}/cert-manager/${CERT_MANAGER_VERSION}/cert-manager.yaml
  version: ${CERT_MANAGER_VERSION}
EOF

# Dockerfile.appliance's FROM line follows the lock. Provider versions don't
# need syncing: cmd/appliance reads them from the clusterctl repository.
sed -i.bak \
    -e "s|^ARG K3S_IMAGE=.*|ARG K3S_IMAGE=rancher/k3s:${K3S_VERSION}@${k3s_digest}|" \
    "${ROOT}/Dockerfile.appliance"
rm -f "${ROOT}/Dockerfile.appliance.bak"

echo "Updated appliance/assets.lock, appliance/clusterctl.yaml and Dockerfile.appliance" >&2
